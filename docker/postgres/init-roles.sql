-- PostgreSQL initialization script for non-superuser API role
CREATE ROLE cirra_app WITH LOGIN PASSWORD 'cirrapassword' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
GRANT ALL PRIVILEGES ON DATABASE cirra TO cirra_app;

\c cirra

GRANT ALL ON SCHEMA public TO cirra_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO cirra_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO cirra_app;
