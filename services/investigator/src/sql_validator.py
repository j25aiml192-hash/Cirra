import re
import sqlparse
from sqlparse.sql import IdentifierList, Identifier, Where
from sqlparse.tokens import DML, Keyword


class SQLValidationError(Exception):
    pass


ALLOWED_TABLES = {"cost_facts", "ai_usage_facts"}
FORBIDDEN_COMMANDS = {"insert", "update", "delete", "drop", "alter", "create", "truncate", "replace"}


def validate_sql(raw_sql: str, tenant_id: str) -> str:
    """
    Validates and sanitizes SQL queries generated by LLMs before execution on ClickHouse.
    1. Enforces read-only SELECT statement.
    2. Enforces table allow-list (only cost_facts and ai_usage_facts).
    3. Guarantees tenant_id filter injection.
    4. Limits rows to max 1000.
    """
    cleaned = raw_sql.strip().rstrip(";")
    parsed = sqlparse.parse(cleaned)

    if not parsed:
        raise SQLValidationError("Empty SQL query")

    stmt = parsed[0]

    # 1. Enforce SELECT statement only
    if stmt.get_type() != "SELECT":
        raise SQLValidationError("Only read-only SELECT queries are allowed")

    sql_lower = cleaned.lower()

    # Reject forbidden mutations
    for cmd in FORBIDDEN_COMMANDS:
        if re.search(rf"\b{cmd}\b", sql_lower):
            raise SQLValidationError(f"Forbidden SQL command: {cmd.upper()}")

    # 2. Table allow-list check
    tables_found = set(re.findall(r"\bfrom\s+([a-zA-Z0-9_]+)", sql_lower))
    tables_found.update(re.findall(r"\bjoin\s+([a-zA-Z0-9_]+)", sql_lower))

    for tbl in tables_found:
        if tbl not in ALLOWED_TABLES:
            raise SQLValidationError(f"Unauthorized table access: '{tbl}'. Allowed: {ALLOWED_TABLES}")

    # 3. Inject tenant_id condition
    tenant_clause = f"tenant_id = '{tenant_id}'"
    if "where" in sql_lower:
        # Inject at beginning of WHERE
        final_sql = re.sub(
            r"\bwhere\b",
            f"WHERE {tenant_clause} AND",
            cleaned,
            count=1,
            flags=re.IGNORECASE,
        )
    else:
        # Find position after FROM table
        for tbl in ALLOWED_TABLES:
            if tbl in sql_lower:
                final_sql = re.sub(
                    rf"(\bfrom\s+{tbl}\b)",
                    rf"\1 WHERE {tenant_clause}",
                    cleaned,
                    count=1,
                    flags=re.IGNORECASE,
                )
                break
        else:
            final_sql = f"{cleaned} WHERE {tenant_clause}"

    # 4. Enforce LIMIT 1000
    if not re.search(r"\blimit\s+\d+\b", final_sql.lower()):
        final_sql = f"{final_sql} LIMIT 1000"
    else:
        # Ensure limit does not exceed 1000
        final_sql = re.sub(
            r"\blimit\s+(\d+)\b",
            lambda m: f"LIMIT {min(int(m.group(1)), 1000)}",
            final_sql,
            flags=re.IGNORECASE,
        )

    return final_sql
